CREATE TABLE IF NOT EXISTS ts_users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL, password_hash VARCHAR(255) NOT NULL DEFAULT '',
 display_name VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'user',
 telegram_id BIGINT NULL, status TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL, last_login_at DATETIME NULL,
 UNIQUE KEY uq_username(username), UNIQUE KEY uq_telegram(telegram_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS ts_sessions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL, csrf_token CHAR(48) NOT NULL, scope VARCHAR(20) NOT NULL,
 expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL,
 UNIQUE KEY uq_token(token_hash), KEY idx_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_categories (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL,
 description VARCHAR(255) NOT NULL DEFAULT '', sort_order INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL, UNIQUE KEY uq_name(name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_resources (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, title VARCHAR(180) NOT NULL,
 description TEXT NOT NULL, url VARCHAR(500) NOT NULL, url_hash CHAR(64) NOT NULL,
 type VARCHAR(20) NOT NULL DEFAULT 'channel', category_id BIGINT UNSIGNED NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'published', members BIGINT UNSIGNED NULL,
 tags VARCHAR(255) NOT NULL DEFAULT '', featured TINYINT NOT NULL DEFAULT 0,
 source VARCHAR(30) NOT NULL DEFAULT 'admin', owner_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 UNIQUE KEY uq_url(url_hash), KEY idx_status_type(status,type,id), KEY idx_category(category_id,status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS ts_submissions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL, url VARCHAR(500) NOT NULL, type VARCHAR(20) NOT NULL,
 description TEXT NOT NULL, category_id BIGINT UNSIGNED NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', review_note VARCHAR(500) NOT NULL DEFAULT '',
 resource_id BIGINT UNSIGNED NULL, reviewer_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL, reviewed_at DATETIME NULL,
 KEY idx_status(status,id), KEY idx_user(user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_favorites (
 user_id BIGINT UNSIGNED NOT NULL, resource_id BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL,
 PRIMARY KEY(user_id,resource_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_search_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, query VARCHAR(120) NOT NULL,
 source VARCHAR(20) NOT NULL, result_count INT UNSIGNED NOT NULL DEFAULT 0,
 duration_ms INT UNSIGNED NOT NULL DEFAULT 0, created_at DATETIME NOT NULL,
 KEY idx_time(created_at), KEY idx_query(query,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_settings (
 name VARCHAR(80) NOT NULL PRIMARY KEY, value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_audit_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NULL,
 action VARCHAR(100) NOT NULL, detail VARCHAR(500) NOT NULL DEFAULT '', created_at DATETIME NOT NULL,
 KEY idx_time(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_api_keys (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL,
 token_hash CHAR(64) NOT NULL, prefix VARCHAR(16) NOT NULL, status TINYINT NOT NULL DEFAULT 1,
 daily_limit INT NOT NULL DEFAULT 1000, created_at DATETIME NOT NULL, last_used_at DATETIME NULL,
 UNIQUE KEY uq_token(token_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_rate_limits (
 bucket VARCHAR(180) NOT NULL PRIMARY KEY, hits INT UNSIGNED NOT NULL, expires_at DATETIME NOT NULL,
 KEY idx_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_bot_updates (
 bot_id BIGINT NOT NULL, update_id BIGINT NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'processing',
 created_at DATETIME NOT NULL, completed_at DATETIME NULL, PRIMARY KEY(bot_id,update_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_bot_sessions (
 id CHAR(24) NOT NULL PRIMARY KEY, telegram_user_id BIGINT NOT NULL, chat_id BIGINT NOT NULL,
 message_id BIGINT NULL, query VARCHAR(120) NOT NULL, type VARCHAR(20) NOT NULL DEFAULT '',
 page INT NOT NULL DEFAULT 1, revision INT NOT NULL DEFAULT 1,
 expires_at DATETIME NOT NULL, KEY idx_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
