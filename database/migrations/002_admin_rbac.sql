CREATE TABLE IF NOT EXISTS ts_admins (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 display_name VARCHAR(100) NOT NULL, status TINYINT NOT NULL DEFAULT 1,
 is_super TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL, last_login_at DATETIME NULL,
 UNIQUE KEY uq_admin_username(username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS ts_admin_sessions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL,
 csrf_token CHAR(48) NOT NULL, expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL,
 UNIQUE KEY uq_admin_token(token_hash), KEY idx_admin_session(admin_id), KEY idx_expiry(expires_at),
 CONSTRAINT fk_admin_session FOREIGN KEY (admin_id) REFERENCES ts_admins(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_roles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL, description VARCHAR(255) NOT NULL DEFAULT '',
 status TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 UNIQUE KEY uq_role_name(name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_admin_roles (
 admin_id BIGINT UNSIGNED NOT NULL, role_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(admin_id,role_id),
 CONSTRAINT fk_admin_role_admin FOREIGN KEY(admin_id) REFERENCES ts_admins(id) ON DELETE CASCADE,
 CONSTRAINT fk_admin_role_role FOREIGN KEY(role_id) REFERENCES ts_roles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_role_permissions (
 role_id BIGINT UNSIGNED NOT NULL, permission VARCHAR(100) NOT NULL,
 PRIMARY KEY(role_id,permission),
 CONSTRAINT fk_role_permission FOREIGN KEY(role_id) REFERENCES ts_roles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_role_fields (
 role_id BIGINT UNSIGNED NOT NULL, resource VARCHAR(40) NOT NULL, field VARCHAR(80) NOT NULL,
 can_read TINYINT NOT NULL DEFAULT 0, can_write TINYINT NOT NULL DEFAULT 0,
 PRIMARY KEY(role_id,resource,field),
 CONSTRAINT fk_role_field FOREIGN KEY(role_id) REFERENCES ts_roles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ts_schema_migrations (
 version VARCHAR(80) NOT NULL PRIMARY KEY, applied_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
