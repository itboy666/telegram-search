CREATE TABLE IF NOT EXISTS ts_bot_groups (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  bot_id BIGINT UNSIGNED NOT NULL,
  chat_id BIGINT NOT NULL,
  title VARCHAR(255) NOT NULL DEFAULT '',
  inviter_id BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'member',
  can_delete TINYINT UNSIGNED NOT NULL DEFAULT 0,
  verify_mode VARCHAR(16) NOT NULL DEFAULT 'inherit',
  ad_mode VARCHAR(16) NOT NULL DEFAULT 'off',
  ad_keywords TEXT NOT NULL,
  allow_domains TEXT NOT NULL,
  flood_limit TINYINT UNSIGNED NOT NULL DEFAULT 0,
  blocked_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  last_error VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY bot_chat (bot_id, chat_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ts_bot_verifications (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  bot_id BIGINT UNSIGNED NOT NULL,
  chat_id BIGINT NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  challenge_id CHAR(32) NULL,
  method VARCHAR(16) NOT NULL DEFAULT '',
  policy_hash CHAR(64) NOT NULL DEFAULT '',
  state VARCHAR(16) NOT NULL DEFAULT 'new',
  answer_hashes TEXT NOT NULL,
  payload TEXT NOT NULL,
  pending_query VARCHAR(120) NOT NULL DEFAULT '',
  reply_context TEXT NOT NULL,
  message_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
  thread_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  step TINYINT UNSIGNED NOT NULL DEFAULT 0,
  issued_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
  challenge_until BIGINT UNSIGNED NOT NULL DEFAULT 0,
  verified_until BIGINT UNSIGNED NOT NULL DEFAULT 0,
  blocked_until BIGINT UNSIGNED NOT NULL DEFAULT 0,
  expires_at DATETIME NOT NULL,
  UNIQUE KEY identity_scope (bot_id, chat_id, user_id),
  UNIQUE KEY challenge (challenge_id),
  KEY expiration (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
