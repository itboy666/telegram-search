CREATE TABLE IF NOT EXISTS ts_bot_join_challenges (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  bot_id BIGINT UNSIGNED NOT NULL,
  chat_id BIGINT NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  challenge_id CHAR(32) NOT NULL,
  event_at BIGINT NOT NULL DEFAULT 0,
  last_update_id BIGINT NOT NULL DEFAULT 0,
  state VARCHAR(24) NOT NULL DEFAULT 'issuing',
  method VARCHAR(16) NOT NULL DEFAULT 'off',
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts TINYINT UNSIGNED NOT NULL DEFAULT 3,
  step TINYINT UNSIGNED NOT NULL DEFAULT 0,
  failure_action VARCHAR(8) NOT NULL DEFAULT 'mute',
  answer_hashes TEXT NOT NULL,
  payload TEXT NOT NULL,
  user_profile TEXT NOT NULL,
  chat_profile TEXT NOT NULL,
  private_message_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
  private_generation CHAR(12) NOT NULL DEFAULT '',
  welcome_message_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
  restriction_owned TINYINT UNSIGNED NOT NULL DEFAULT 0,
  restriction_confirmed TINYINT UNSIGNED NOT NULL DEFAULT 0,
  manual_override TINYINT UNSIGNED NOT NULL DEFAULT 0,
  expected_permissions TEXT NOT NULL,
  last_error VARCHAR(500) NOT NULL DEFAULT '',
  expires_at DATETIME NOT NULL,
  lease_until DATETIME NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY identity_scope (bot_id,chat_id,user_id),
  UNIQUE KEY challenge (challenge_id),
  KEY due_challenges (bot_id,state,expires_at),
  KEY stale_leases (bot_id,state,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
